let locale = 'en';

function resolve(pref, systemLocale) {
  const p = String(pref || 'auto').toLowerCase();
  if (DICT[p]) return p;
  return String(systemLocale || '').toLowerCase().startsWith('ko') ? 'ko' : 'en';
}

function setLocale(pref, systemLocale) { locale = resolve(pref, systemLocale); return locale; }
function getLocale() { return locale; }

function format(s, params) {
  return String(s).replace(/\{(\w+)\}/g, (_, k) => (params && params[k] !== undefined && params[k] !== null ? params[k] : ''));
}

function t(key, params) {
  const s = (DICT[locale] && DICT[locale][key]) ?? DICT.en[key] ?? key;
  return format(s, params);
}

/** 렌더러로 보낼 현재 언어 사전 */
function dictionary() { return { locale, dict: { ...DICT.en, ...(DICT[locale] || {}) } }; }

module.exports = { t, setLocale, getLocale, dictionary, format, LOCALES: Object.keys(DICT) };
